import json
import os
import hmac
from http.server import BaseHTTPRequestHandler

import requests

SUPABASE_URL = os.environ.get("SUPABASE_URL", "").rstrip("/")
SUPABASE_SERVICE_ROLE_KEY = os.environ.get("SUPABASE_SERVICE_ROLE_KEY", "")
TABLE = "market_history_state"
TIMEOUT = 15
MAX_BODY = 128 * 1024
WRITE_TOKEN = os.environ.get("MARKET_HISTORY_WRITE_TOKEN", "")


def sb_request(method, path, *, params=None, payload=None, prefer=None, public=False):
    if not SUPABASE_URL:
        raise RuntimeError("Supabase URL is not configured.")
    if public and os.environ.get("SUPABASE_PUBLISHABLE_KEY", "").strip():
        headers = {
            "apikey": os.environ["SUPABASE_PUBLISHABLE_KEY"].strip(),
            "Accept": "application/json",
        }
    else:
        if not SUPABASE_SERVICE_ROLE_KEY:
            raise RuntimeError("Supabase server credentials are not configured.")
        headers = {
            "apikey": SUPABASE_SERVICE_ROLE_KEY,
            "Authorization": f"Bearer {SUPABASE_SERVICE_ROLE_KEY}",
            "Accept": "application/json",
        }
    if payload is not None:
        headers["Content-Type"] = "application/json"
    if prefer:
        headers["Prefer"] = prefer
    response = requests.request(
        method,
        f"{SUPABASE_URL}/rest/v1/{path}",
        params=params,
        json=payload,
        headers=headers,
        timeout=TIMEOUT,
    )
    if not response.ok:
        raise RuntimeError(f"Supabase request failed ({response.status_code}).")
    if response.status_code == 204 or not response.content:
        return None
    return response.json()


def respond(handler, status, payload):
    body = json.dumps(payload, ensure_ascii=False).encode("utf-8")
    handler.send_response(status)
    handler.send_header("Content-Type", "application/json; charset=utf-8")
    handler.send_header("Cache-Control", "no-store")
    handler.send_header("Access-Control-Allow-Origin", "*")
    handler.send_header("Access-Control-Allow-Methods", "GET, POST, OPTIONS")
    handler.send_header("Access-Control-Allow-Headers", "Content-Type, Accept, X-Market-History-Token, x-vercel-protection-bypass")
    handler.send_header("Content-Length", str(len(body)))
    handler.end_headers()
    if status != 204:
        handler.wfile.write(body)


class handler(BaseHTTPRequestHandler):
    def do_OPTIONS(self):
        respond(self, 204, {})

    def do_GET(self):
        try:
            rows = sb_request(
                "GET",
                TABLE,
                params={"id": "eq.daily", "select": "state,updated_at", "limit": "1"},
                public=True,
            ) or []
            if not rows:
                respond(self, 200, {"ok": True, "found": False, "state": None})
                return
            respond(self, 200, {
                "ok": True,
                "found": True,
                "state": rows[0].get("state"),
                "updatedAt": rows[0].get("updated_at"),
            })
        except Exception as exc:
            print("MARKET HISTORY GET ERROR:", str(exc)[:300])
            respond(self, 500, {"ok": False, "error": "خواندن تاریخچه بازار از پایگاه داده ناموفق بود."})

    def do_POST(self):
        supplied_token = self.headers.get("X-Market-History-Token", "")
        if not WRITE_TOKEN or not hmac.compare_digest(supplied_token, WRITE_TOKEN):
            respond(self, 401, {"ok": False, "error": "دسترسی نوشتن مجاز نیست."})
            return
        try:
            length = int(self.headers.get("Content-Length", "0"))
            if length <= 0 or length > MAX_BODY:
                respond(self, 413, {"ok": False, "error": "اندازه درخواست معتبر نیست."})
                return
            raw = self.rfile.read(length)
            data = json.loads(raw.decode("utf-8"))
            state = data.get("state") if isinstance(data, dict) else None
            if (
                not isinstance(state, dict)
                or not isinstance(state.get("days"), dict)
                or not isinstance(state.get("latest"), (dict, type(None)))
            ):
                respond(self, 400, {"ok": False, "error": "ساختار تاریخچه بازار معتبر نیست."})
                return
            row = {
                "id": "daily",
                "state": state,
                "updated_at": "now()",
            }
            # PostgREST cannot accept the SQL now() expression as a timestamp;
            # use a UTC ISO timestamp generated by Python instead.
            from datetime import datetime, timezone
            row["updated_at"] = datetime.now(timezone.utc).isoformat()
            sb_request(
                "POST",
                TABLE,
                payload=row,
                prefer="resolution=merge-duplicates,return=minimal",
            )
            respond(self, 200, {"ok": True, "saved": True})
        except (ValueError, UnicodeDecodeError, json.JSONDecodeError):
            respond(self, 400, {"ok": False, "error": "درخواست JSON معتبر نیست."})
        except Exception as exc:
            print("MARKET HISTORY SAVE ERROR:", str(exc)[:300])
            respond(self, 500, {"ok": False, "error": "ذخیره تاریخچه بازار در پایگاه داده ناموفق بود."})

    def log_message(self, fmt, *args):
        print("HTTP:", fmt % args)

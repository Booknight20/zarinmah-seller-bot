create table if not exists public.seller_subscriptions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  payment_order_id bigint not null unique references public.seller_payment_orders(id) on delete restrict,
  package_code text not null,
  package_name text not null,
  price_toman bigint not null check (price_toman > 0),
  listing_limit integer not null check (listing_limit > 0),
  starts_at timestamptz not null default now(),
  ends_at timestamptz not null,
  status text not null default 'active' check (status in ('active','expired','cancelled')),
  created_at timestamptz not null default now()
);
create index if not exists seller_subscriptions_user_status_idx on public.seller_subscriptions(user_id,status,ends_at desc);
alter table public.seller_subscriptions enable row level security;
drop policy if exists "Users can read own seller subscriptions" on public.seller_subscriptions;
create policy "Users can read own seller subscriptions" on public.seller_subscriptions for select to authenticated using(user_id=(select auth.uid()));
drop policy if exists "Admins can read seller subscriptions" on public.seller_subscriptions;
create policy "Admins can read seller subscriptions" on public.seller_subscriptions for select to authenticated using(private.zarinmah_is_admin());
grant select on public.seller_subscriptions to authenticated;

create or replace function public.zarinmah_create_seller_package_order(p_package_code text)
returns jsonb language plpgsql security definer
set search_path=pg_catalog,public,auth,private
as $$
declare v_uid uuid:=auth.uid(); v_tariff jsonb; v_payment jsonb; v_package jsonb;
  v_order public.seller_payment_orders%rowtype; v_code text:=trim(coalesce(p_package_code,''));
  v_price bigint; v_limit integer; v_days integer;
begin
  if v_uid is null then raise exception 'برای خرید اشتراک ابتدا وارد حساب کاربری شوید.'; end if;
  select setting_value into v_tariff from public.zarinmah_site_settings where setting_key='seller_tariff_config';
  select setting_value into v_payment from public.zarinmah_site_settings where setting_key='seller_payment_config';
  if coalesce((v_payment->>'enabled')::boolean,false) is not true
     or coalesce(v_payment->>'method','')<>'manual_card_transfer'
     or length(coalesce(v_payment->>'card_number',''))<>16
     or length(coalesce(v_payment->>'card_owner',''))<3 then
    raise exception 'پرداخت کارت‌به‌کارت اشتراک در حال حاضر فعال نیست.';
  end if;
  select p into v_package from jsonb_array_elements(coalesce(v_tariff->'packages','[]'::jsonb)) p
    where p->>'code'=v_code and coalesce((p->>'active')::boolean,false)=true limit 1;
  if v_package is null then raise exception 'این طرح در حال حاضر قابل خرید نیست.'; end if;
  v_price:=nullif(v_package->>'price_toman','')::bigint;
  v_limit:=nullif(v_package->>'listing_limit','')::integer;
  v_days:=nullif(v_package->>'duration_days','')::integer;
  if coalesce(v_price,0)<=0 or coalesce(v_limit,0)<=0 or coalesce(v_days,0)<=0 then raise exception 'اطلاعات طرح اشتراک معتبر نیست.'; end if;
  insert into public.seller_payment_orders(user_id,purpose,package_code,package_name,amount_toman,payment_method,provider,status,metadata)
  values(v_uid,'package_purchase',v_code,left(v_package->>'name',100),v_price,'manual_card_transfer','manual_card_transfer','awaiting_receipt',
    jsonb_build_object('package_code',v_code,'package_name',v_package->>'name','package_price_toman',v_price,
      'package_listing_limit',v_limit,'package_duration_days',v_days,'payment_card_number',v_payment->>'card_number',
      'payment_card_owner',v_payment->>'card_owner','payment_instructions',v_payment->>'instructions'))
  returning * into v_order;
  return to_jsonb(v_order);
end;
$$;
revoke all on function public.zarinmah_create_seller_package_order(text) from public,anon;
grant execute on function public.zarinmah_create_seller_package_order(text) to authenticated;

create or replace function public.zarinmah_admin_review_seller_payment(p_order_id bigint,p_action text,p_rejection_reason text default null)
returns jsonb language plpgsql security definer set search_path=pg_catalog,public,auth,private as $$
declare v_user_id uuid:=auth.uid(); v_order public.seller_payment_orders%rowtype; v_listing_id bigint;
  v_reason text:=trim(coalesce(p_rejection_reason,'')); v_new_status text; v_meta jsonb; v_days integer;
begin
  if v_user_id is null or not private.zarinmah_is_admin() then raise exception 'فقط مدیرکل می‌تواند رسید پرداخت را بررسی کند.'; end if;
  if coalesce(p_action,'') not in ('approve','reject') then raise exception 'عملیات بررسی پرداخت معتبر نیست.'; end if;
  select * into v_order from public.seller_payment_orders where id=p_order_id for update;
  if not found then raise exception 'سفارش پرداخت پیدا نشد.'; end if;
  if v_order.status<>'under_review' or v_order.receipt_path is null then raise exception 'فقط رسیدهای ارسال‌شده و در انتظار بررسی قابل تصمیم‌گیری هستند.'; end if;
  if p_action='reject' and length(v_reason)<4 then raise exception 'برای رد رسید، دلیل کوتاهی وارد کنید.'; end if;
  v_new_status:=case when p_action='approve' then 'approved' else 'rejected' end;
  if p_action='approve' and v_order.purpose='listing_fee' and v_order.listing_id is not null then
    update public.listings set payment_status='paid',updated_at=now()
      where id=v_order.listing_id and owner_user_id=v_order.user_id and payment_status='awaiting_payment' returning id into v_listing_id;
    if v_listing_id is null then raise exception 'آگهی مرتبط پیدا نشد یا وضعیت پرداخت آن تغییر کرده است.'; end if;
  elsif p_action='approve' and v_order.purpose='package_purchase' then
    v_meta:=coalesce(v_order.metadata,'{}'::jsonb); v_days:=nullif(v_meta->>'package_duration_days','')::integer;
    if coalesce(v_days,0)<=0 or coalesce((v_meta->>'package_listing_limit')::integer,0)<=0 or length(coalesce(v_meta->>'package_code',''))=0 then
      raise exception 'اطلاعات طرح ذخیره‌شده در سفارش معتبر نیست.';
    end if;
    update public.seller_subscriptions set status='expired' where user_id=v_order.user_id and status='active' and ends_at<=now();
    insert into public.seller_subscriptions(user_id,payment_order_id,package_code,package_name,price_toman,listing_limit,starts_at,ends_at,status)
    values(v_order.user_id,v_order.id,v_meta->>'package_code',coalesce(v_meta->>'package_name',v_order.package_name),
      v_order.amount_toman,(v_meta->>'package_listing_limit')::integer,now(),now()+make_interval(days=>v_days),'active');
  end if;
  update public.seller_payment_orders set status=v_new_status,reviewed_by=v_user_id,reviewed_at=now(),updated_at=now(),
    rejection_reason=case when p_action='reject' then v_reason else null end where id=p_order_id returning * into v_order;
  return to_jsonb(v_order);
end;
$$;
revoke all on function public.zarinmah_admin_review_seller_payment(bigint,text,text) from public,anon;
grant execute on function public.zarinmah_admin_review_seller_payment(bigint,text,text) to authenticated;


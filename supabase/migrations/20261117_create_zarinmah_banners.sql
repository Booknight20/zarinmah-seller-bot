create table if not exists public.zarinmah_banners (
  id bigint generated by default as identity primary key,
  title text not null,
  image_url text not null,
  storage_path text,
  target_url text,
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.zarinmah_banners enable row level security;

drop policy if exists "Public can read active ZarinMah banners" on public.zarinmah_banners;
create policy "Public can read active ZarinMah banners"
on public.zarinmah_banners
for select
to anon, authenticated
using (is_active = true);

create index if not exists zarinmah_banners_active_order_idx
on public.zarinmah_banners (is_active, sort_order, created_at desc);

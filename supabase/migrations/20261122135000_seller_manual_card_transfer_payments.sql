-- ZarinMah seller manual card-transfer payments (Staging/Preview migration)
-- Payment gateway fields are reserved for a later provider integration. No gateway is enabled here.

create table if not exists public.seller_payment_orders (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  purpose text not null default 'listing_fee' check (purpose in ('listing_fee','package_purchase')),
  listing_id bigint references public.listings(id) on delete set null,
  package_code text,
  package_name text,
  amount_toman bigint not null check (amount_toman > 0),
  payment_method text not null default 'manual_card_transfer',
  provider text not null default 'manual_card_transfer',
  status text not null default 'awaiting_receipt'
    check (status in ('awaiting_receipt','under_review','approved','rejected','cancelled','expired','gateway_pending','gateway_failed')),
  payer_name text,
  tracking_code text,
  receipt_path text,
  rejection_reason text,
  admin_note text,
  gateway_reference text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  reviewed_by uuid references auth.users(id) on delete set null,
  reviewed_at timestamptz
);

alter table public.listings add column if not exists payment_status text not null default 'free';
alter table public.listings add column if not exists payment_order_id bigint;
alter table public.listings drop constraint if exists listings_payment_status_check;
alter table public.listings add constraint listings_payment_status_check
  check (payment_status in ('free','awaiting_payment','paid','package'));
alter table public.listings drop constraint if exists listings_payment_order_id_fkey;
alter table public.listings add constraint listings_payment_order_id_fkey
  foreign key (payment_order_id) references public.seller_payment_orders(id) on delete set null;

create index if not exists seller_payment_orders_user_created_idx on public.seller_payment_orders(user_id,created_at desc);
create index if not exists seller_payment_orders_status_created_idx on public.seller_payment_orders(status,created_at desc);
create index if not exists seller_payment_orders_listing_idx on public.seller_payment_orders(listing_id);
alter table public.seller_payment_orders enable row level security;


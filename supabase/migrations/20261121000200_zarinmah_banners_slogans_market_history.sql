-- ZarinMah Production: homepage banners, homepage slogan settings, and market price history.
-- All writes are performed by the server through the Supabase service-role key.
-- Public access is limited to active banner rows; settings and market history are private.

create table if not exists public.zarinmah_banners (
  id bigint generated by default as identity primary key,
  title text not null default '',
  image_url text not null,
  storage_path text,
  target_url text,
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.zarinmah_banners enable row level security;
drop policy if exists "Public can read active ZarinMah banners" on public.zarinmah_banners;
create policy "Public can read active ZarinMah banners"
on public.zarinmah_banners
for select
to anon, authenticated
using (is_active = true);

grant select on table public.zarinmah_banners to anon, authenticated;
grant all on table public.zarinmah_banners to service_role;
grant usage, select on sequence public.zarinmah_banners_id_seq to service_role;

create index if not exists zarinmah_banners_active_order_idx
on public.zarinmah_banners (is_active, sort_order, created_at desc);

create table if not exists public.zarinmah_site_settings (
  setting_key text primary key,
  setting_value jsonb not null default '{}'::jsonb,
  updated_by uuid null references auth.users(id) on delete set null,
  updated_at timestamptz not null default now()
);

alter table public.zarinmah_site_settings enable row level security;
revoke all on table public.zarinmah_site_settings from anon, authenticated;
grant all on table public.zarinmah_site_settings to service_role;

create table if not exists public.market_history_state (
  id text primary key check (id = 'daily'),
  state jsonb not null,
  updated_at timestamptz not null default now()
);

alter table public.market_history_state enable row level security;
revoke all on table public.market_history_state from anon, authenticated;
grant all on table public.market_history_state to service_role;

comment on table public.market_history_state is
  'ZarinMah daily market price history state; service-role access only.';
